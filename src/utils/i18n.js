/**
 * Returns translated string for key, falling back to Arabic, then English, then key itself.
 */
export function t(key, fallback = "") {
  const langDict = TRANSLATIONS[_currentLang] || TRANSLATIONS.ar;
  if (langDict[key] !== undefined) return langDict[key];
  if (TRANSLATIONS.ar[key] !== undefined) return TRANSLATIONS.ar[key];
  if (TRANSLATIONS.en[key] !== undefined) return TRANSLATIONS.en[key];
  return fallback || key;
}

