/**
 * Returns localized genre name according to active language (ckb, ar, or en).
 */
export function getLocalizedGenre(genre, lang = _currentLang) {
  if (!genre) return "";
  const id =
    typeof genre === "number"
      ? genre
      : typeof genre === "object"
        ? genre.id
        : null;
  const rawName =
    typeof genre === "object"
      ? genre.name || ""
      : typeof genre === "string"
        ? genre
        : "";

  let targetId = id;
  if (!targetId && rawName) {
    targetId = GENRE_NAME_LOOKUP[rawName.trim().toLowerCase()];
  }
  if (!targetId && rawName) {
    const found = Object.entries(GENRES_I18N).find(
      ([_, v]) =>
        v.ar === rawName ||
        v.ckb === rawName ||
        v.en.toLowerCase() === rawName.toLowerCase(),
    );
    if (found) targetId = Number(found[0]);
  }

  if (targetId && GENRES_I18N[targetId]) {
    const entry = GENRES_I18N[targetId];
    return entry[lang] || entry.ckb || entry.ar || entry.en || rawName;
  }
  return rawName;
}
