// ── hwto-kurd Internationalization (i18n) Engine ──────────────────────────────
import { storage } from "./storage.js";

export const SUPPORTED_LANGUAGES = [
  { code: "ar", label: "العربية", dir: "rtl", flag: "🇸🇦" },
  { code: "ckb", label: "کوردی (سۆرانی)", dir: "rtl", flag: "☀️" },
  { code: "en", label: "English", dir: "ltr", flag: "🇬🇧" },
];

const STORAGE_LANG_KEY = "hwto_app_language";

export function getInitialLanguage() {
  const saved = storage.get(STORAGE_LANG_KEY);
  if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
    return saved;
  }
  return "ar"; // الافتراضي: العربية
}

let _currentLang = getInitialLanguage();
const _listeners = new Set();

export function getCurrentLanguage() {
  return _currentLang;
}

export function getLanguageMeta(code = _currentLang) {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.code === code) || SUPPORTED_LANGUAGES[0]
  );
}

export function isRTL(code = _currentLang) {
  return getLanguageMeta(code).dir === "rtl";
}

export function getLocale(code = _currentLang) {
  return code === "ar" ? "ar-SA" : code === "ckb" ? "ckb-IQ" : "en-US";
}

export function subscribeLanguage(listener) {
  _listeners.add(listener);
  return () => _listeners.delete(listener);
}

export function setLanguage(newCode) {
  if (!SUPPORTED_LANGUAGES.some((l) => l.code === newCode)) return;
  _currentLang = newCode;
  storage.set(STORAGE_LANG_KEY, newCode);

  // Automatically sync TMDB metadata language
  const tmdbLang =
    newCode === "en" ? "en-US" : newCode === "ckb" ? "ku-TR" : "ar-SA";
  storage.set("tmdbLang", tmdbLang);

  // Clear caches so new language metadata is fetched fresh immediately
  try {
    localStorage.removeItem("streambert_trendingCache");
    localStorage.removeItem("streambert_homeLayout");
  } catch {}

  const meta = getLanguageMeta(newCode);
  if (typeof document !== "undefined") {
    document.documentElement.lang = newCode;
    document.documentElement.dir = meta.dir;
  }

  _listeners.forEach((fn) => {
    try {
      fn(newCode, meta);
    } catch {}
  });

  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent("streambert:tmdb-lang-changed"));
  }
}

